def _git(root: Path, *args: str, stdin: str | None = None) -> str:
    """One git command's output, stripped; empty when the command fails."""
    done = subprocess.run(["git", *args], cwd=root, input=stdin, capture_output=True, text=True, check=False)
    return done.stdout.strip() if done.returncode == 0 else ""


def _relative(path: Path, root: Path) -> str:
    try:
        return path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return str(path)


def _planning(root: Path) -> Path:
    return root / SETTINGS["planning_dir"]


def note_dir(root: Path) -> Path:
    return _planning(root) / "handoffs"


def note_path(root: Path, branch: str) -> Path:
    return note_dir(root) / (re.sub(r"[^\w.-]+", "-", branch).strip("-") + ".md")


def other_notes(root: Path) -> list[str]:
    return sorted(p.name for p in note_dir(root).glob("*.md") if p.name != "README.md")


def current_branch(root: Path) -> str:
    return _git(root, "rev-parse", "--abbrev-ref", "HEAD") or "HEAD"


def _state(root: Path) -> dict[str, str]:
    """The phase workflow's STATE.md frontmatter, when the project has one."""
    path = _planning(root) / "STATE.md"
    text = path.read_text(encoding="utf-8") if path.is_file() else ""
    found = {}
    for key in (*STATE_KEYS, "base_branch"):
        match = re.search(rf"^{key}:\s*(.+)$", text, re.MULTILINE)
        if match:
            found[key] = match.group(1).strip().strip('"')
    return found


def _paused(root: Path) -> list[str]:
    return sorted(_relative(p, root) for p in (_planning(root) / "phases").glob("*/.continue-here.md"))


def base_ref(root: Path, base: str) -> str:
    """The ref ``base`` names in this checkout, the local branch or origin's; '' when there is
    none or it shares no history with HEAD."""
    for ref in (base, "origin/" + base):
        if _git(root, "rev-parse", "--verify", "--quiet", ref + "^{commit}") and _git(root, "merge-base", ref, "HEAD"):
            return ref
    return ""


def default_base(root: Path) -> str:
    """The branch work starts from: the setting, the phase workflow's, origin's default, main."""
    named = SETTINGS["base_branch"] or _state(root).get("base_branch", "")
    if named and named != "null":
        return named
    head = _git(root, "symbolic-ref", "--quiet", "--short", "refs/remotes/origin/HEAD")
    if "/" in head:
        return head.split("/", 1)[1]
    return next((name for name in ("main", "master") if base_ref(root, name)), "main")


def snapshot(root: Path, base: str | None = None, *, ignored: list[dict] | None = None) -> dict:
    """What git and the planning folder say about the branch right now. ``ignored`` is an
    inventory already taken, so that one command sizes the ignored files once."""
    base = base or default_base(root)
    ref = base_ref(root, base)
    upstream = _git(root, "rev-parse", "--abbrev-ref", "--symbolic-full-name", "@{u}")
    unpushed = _git(root, "rev-list", "--count", "@{u}..HEAD") if upstream else ""
    status = _git(root, "status", "--porcelain", "--untracked-files=all")
    state = _state(root)
    if ignored is None:
        ignored = [e for e in ignored_inventory(root, since=branch_start(root, base))
                   if e["kind"] not in {"rebuild", "old"}]
    return {
        "branch": current_branch(root),
        "base": base,
        "head": _git(root, "rev-parse", "--short", "HEAD"),
        "remote": _git(root, "remote", "get-url", "origin"),
        "upstream": upstream,
        "unpushed": int(unpushed) if unpushed.isdigit() else None,
        "ahead_of_base": int(_git(root, "rev-list", "--count", f"{ref}..HEAD") or 0) if ref else None,
        "commits": _git(root, "log", "--oneline", "-15", f"{ref}..HEAD").splitlines() if ref else [],
        "dirty": [line.split(None, 1)[1] for line in status.splitlines() if " " in line.strip()],
        "stashes": len(_git(root, "stash", "list").splitlines()),
        "state": {key: state[key] for key in STATE_KEYS if key in state},
        "ignored": ignored,
        "paused_phases": _paused(root),
        "instructions": [name for name in INSTRUCTION_FILES if (root / name).is_file()],
    }


def _size(root: Path, rel: str) -> tuple[int, int, float, list[str]]:
    """(bytes, files, newest mtime, key paths inside) for an ignored file or folder; links are not
    followed. What looks like a key file or a folder of them inside a folder is listed, with a
    folder ending in /, and left out of the counts: it is not carried with the folder."""
    path = root / rel
    if not path.is_dir() or path.is_symlink():
        stat = path.lstat() if path.exists() or path.is_symlink() else None
        return (stat.st_size, 1, stat.st_mtime, []) if stat else (0, 0, 0.0, [])
    total, count, newest, keys = 0, 0, 0.0, []
    for folder, dirs, names in os.walk(path):
        inside = Path(folder).relative_to(root).as_posix()
        for name in sorted(dirs):
            if _KEY_FILE.search(f"{inside}/{name}"):
                keys.append(f"{inside}/{name}/")
                dirs.remove(name)
        for name in names:
            if _KEY_FILE.search(f"{inside}/{name}"):
                keys.append(f"{inside}/{name}")
                continue
            try:
                stat = (Path(folder) / name).lstat()
            except OSError:  # the file went away while the folder was read
                continue
            total, count = total + stat.st_size, count + 1
            newest = max(newest, stat.st_mtime)
    return total, count, newest, sorted(keys)


def branch_start(root: Path, base: str | None = None) -> float | None:
    """Commit time of the point where the branch left ``base``; None when unknown."""
    ref = base_ref(root, base or default_base(root))
    stamp = _git(root, "log", "-1", "--format=%ct", _git(root, "merge-base", ref, "HEAD")) if ref else ""
    return float(stamp) if stamp.isdigit() else None


def _rebuilt(rel: str) -> bool:
    prefixes = REBUILD_PREFIXES + tuple(SETTINGS["rebuild_paths"])
    return bool(set(PurePosixPath(rel).parts) & REBUILD_NAMES) or rel.endswith(REBUILD_SUFFIXES) \
        or any(rel == p or rel.startswith(p.rstrip("/") + "/") for p in prefixes)


def _max_bytes(max_mb: float | None) -> float:
    return (SETTINGS["max_mb"] if max_mb is None else max_mb) * 1024 * 1024


def _key_path(rel: str) -> bool:
    """The path, or a folder above it, looks like a key file or a folder of them."""
    parts = PurePosixPath(rel).parts
    return any(_KEY_FILE.search("/".join(parts[:end])) for end in range(1, len(parts) + 1))


def _entry(root: Path, rel: str, *, max_mb: float | None, since: float | None, asked: bool = False) -> dict:
    """One ignored path, sorted into its kind. ``asked`` is a path ``--include`` names itself: it
    is sized, dated and searched for key files like any other, even where it would otherwise be
    left to be rebuilt."""
    if _rebuilt(rel) and not asked:
        return {"path": rel, "kind": "rebuild", "bytes": 0, "files": 0}
    kind = "key" if _key_path(rel) else "carry"
    size, files, newest, keys = _size(root, rel) if kind == "carry" else (*_size(root, rel)[:3], [])
    if kind == "carry" and since is not None and newest < since:
        kind = "old"
    elif kind == "carry" and size > _max_bytes(max_mb):
        kind = "large"
    return {"path": rel, "kind": kind, "bytes": size, "files": files, **({"keys": keys} if keys else {})}


_GLOB = re.compile(r"[*?\[]")


def _above(rel: str) -> list[str]:
    """The path and every folder above it, outermost first: a/b/c gives a, a/b, a/b/c."""
    parts = rel.rstrip("/").split("/")
    return ["/".join(parts[:end]) for end in range(1, len(parts) + 1)]


def _named(rel: str, names: list[str]) -> bool:
    """A name or glob of ``--include`` selects this path: it, a folder above it, or a match."""
    bare = rel.rstrip("/")
    return any(bare == g or bare.startswith(g + "/") or fnmatch.fnmatch(bare, g) or fnmatch.fnmatch(bare, g + "/*")
               for g in names)


def _narrow(root: Path, rel: str, include: list[str]) -> list[str]:
    """The parts of the ignored path ``rel`` that ``include`` asks for: all of it when a pattern
    names it or a folder above it, else what the patterns name inside it (a folder ends in /).

    A name matches whole, so ``runs`` is not ``runs-private``. A glob is fnmatch's, where ``*``
    also crosses ``/``; it selects a matching folder whole, else the matching files, and does not
    reach into a path left to be rebuilt. Neither reaches through a link: a link can be named,
    what lies behind it cannot."""
    names = [g.rstrip("/") for g in include if g.rstrip("/")]
    if _named(rel, names):
        return [rel]
    if not rel.endswith("/"):
        return []
    found = set()
    for name in names:
        inside = root / name
        if name.startswith(rel) and _safe(name) and os.path.lexists(inside) \
                and not any((root / above).is_symlink() for above in _above(name)[:-1]):
            found.add(name + "/" if inside.is_dir() and not inside.is_symlink() else name)
    globs = [g for g in names if _GLOB.search(g)]
    for folder, dirs, files in os.walk(root / rel) if globs and not _rebuilt(rel) else ():
        here = Path(folder).relative_to(root).as_posix()
        for name in sorted(dirs):
            if any(fnmatch.fnmatch(f"{here}/{name}", g) for g in globs):
                found.add(f"{here}/{name}" + ("" if (Path(folder) / name).is_symlink() else "/"))
                dirs.remove(name)
        found.update(f"{here}/{name}" for name in files if any(fnmatch.fnmatch(f"{here}/{name}", g) for g in globs))
    folders = tuple(path for path in found if path.endswith("/"))
    return sorted(path for path in found if not any(path != folder and path.startswith(folder) for folder in folders))


def ignored_inventory(root: Path, *, max_mb: float | None = None, since: float | None = None,
                      include: list[str] | None = None) -> list[dict]:
    """Files git ignores in this checkout: {path, kind, bytes, files}, largest first.

    kind is ``carry`` (another checkout lacks it and cannot rebuild it), ``rebuild``
    (environments, caches, other worktrees), ``key`` (looks like a credential file),
    ``old`` (nothing in it changed after ``since``, so this branch did not produce it) or
    ``large`` (over ``max_mb``). Directories git ignores whole are one entry ending in /; such
    an entry has ``keys``, the key paths inside it, when there are any.

    ``include`` narrows the list to the paths and globs it names, which may lie inside an ignored
    folder (see ``_narrow``). A path it names exactly is never ``rebuild``: it gets the kind its
    name, size and age give it.
    """
    listed = _git(root, "ls-files", "-z", "--others", "--ignored", "--exclude-standard",
                  "--directory", "--no-empty-directory")
    asked = {g.rstrip("/") for g in include or []}
    entries = [_entry(root, part, max_mb=max_mb, since=since, asked=part.rstrip("/") in asked)
               for rel in filter(None, listed.split("\0"))
               for part in (_narrow(root, rel, include) if include else [rel])]
    return sorted(entries, key=lambda e: (-e["bytes"], e["path"]))


def _safe(rel) -> bool:
    """A path another host named that stays inside the checkout and names something in it."""
    if not isinstance(rel, str) or not rel or rel.startswith(("/", "~", "-")) or "\n" in rel or "\0" in rel:
        return False
    norm = PurePosixPath(rel).as_posix()
    return norm != "." and ".." not in PurePosixPath(rel).parts and rel.rstrip("/") == norm


def _recheck(root: Path, entries: list, include: list[str] | None = None) -> list[dict]:
    """A listing another host sent, held to this checkout's rules. A path that leaves the checkout
    or names the checkout itself is dropped. What looks like a key file or a rebuildable path here
    is treated as one, unless ``include`` names the rebuildable path exactly, and a path that
    ``include`` did not ask for is dropped. A path this checkout does not ignore is ``refused``:
    only ignored files are ever copied."""
    kept, asked = [], {g.rstrip("/") for g in include or []}
    for entry in entries if isinstance(entries, list) else []:
        rel = entry.get("path") if isinstance(entry, dict) else None
        if not _safe(rel) or (include and not _named(rel, [g for g in asked if g])):
            continue
        kind = ("rebuild" if _rebuilt(rel) and rel.rstrip("/") not in asked
                else "key" if _key_path(rel) else entry.get("kind"))
        if kind not in {"carry", "rebuild", "key", "old", "large"}:
            continue
        inside = [k for k in entry.get("keys") or [] if _safe(k) and rel.endswith("/") and k.startswith(rel)]
        try:
            size, files = int(entry.get("bytes") or 0), int(entry.get("files") or 0)
        except (TypeError, ValueError):
            size, files = 0, 0
        kept.append({"path": rel, "kind": kind, "bytes": size, "files": files, **({"keys": inside} if inside else {})})
    ignored = set(_git(root, "check-ignore", "--no-index", "-z", "--stdin",
                       stdin="\0".join(e["path"] for e in kept)).split("\0")) if kept else set()
    return [e if e["path"] in ignored else {**e, "kind": "refused"} for e in kept]


def _mb(size: int) -> str:
    return f"{size / 1024 / 1024:.1f} MB"


def _n(count: int, noun: str, plural: str = "s") -> str:
    return f"{count} {noun}{'' if count == 1 else plural}"


def _in_the_way(dest: Path, name: str) -> bool:
    """Something in the checkout at ``dest`` keeps a file from being written at ``name`` and
    nowhere else: a link or a file where a folder belongs, or a link or a folder where the file
    goes."""
    *folders, _ = _above(name)
    return (dest / name).is_symlink() or (dest / name).is_dir() or any(
        (dest / f).is_symlink() or (os.path.lexists(dest / f) and not (dest / f).is_dir()) for f in folders)


def _copy_local(root: Path, dest: Path, paths: list[str], exclude: list[str]) -> tuple[int, list[str]]:
    """Copy files under ``paths`` into ``dest``, leaving out ``exclude`` and what lies under it; a
    newer file at the destination stays. A link is copied as a link, never followed, and only
    where nothing is in its place. Returns how many were copied and the ones refused because a
    link or another kind of file at the destination was in the way: a file is written at its own
    name or not at all."""
    copied, refused, left = 0, [], {e.rstrip("/") for e in exclude}
    for rel in paths:
        source = root / rel
        files = [source] if source.is_symlink() or not source.is_dir() \
            else sorted(p for p in source.rglob("*") if p.is_symlink() or p.is_file())
        for file in files:
            name = file.relative_to(root).as_posix()
            target = dest / name
            if left.intersection(_above(name)) or (file.is_symlink() and target.is_symlink()
                                                   and os.readlink(file) == os.readlink(target)):
                continue
            if _in_the_way(dest, name):
                refused.append(name)
                continue
            if target.exists() and (file.is_symlink() or target.stat().st_mtime >= file.lstat().st_mtime):
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(file, target, follow_symlinks=False)
            copied += 1
    return copied, refused


def _is_remote(location: str) -> bool:
    return re.match(r"^[\w.@-]+:.+", location) is not None and not Path(location).exists()


def _tracked(root: Path) -> list[str]:
    """Every file git tracks in the checkout at ``root``."""
    return _git(root, "ls-files", "-z").split("\0")


def _clash(source: Path, tracked: str) -> str | None:
    """What a copy from ``source`` would put in the place of a path the receiving checkout tracks:
    the path itself when ``source`` has it, or the file or link ``source`` has above it. None when
    ``source`` has nothing there."""
    for here in _above(tracked):
        if not os.path.lexists(source / here):
            return None
        if (source / here).is_symlink() or not (source / here).is_dir():
            return here
    return tracked


def _plan(entries: list[dict], with_keys: bool, tracked=(), source: Path | None = None) -> dict:
    """Which ignored entries to copy, and which are left with the reason.

    ``tracked`` is what the receiving checkout tracks. A copy never replaces such a file, whatever
    the sending checkout ignores. An entry at or under a tracked path is left out whole (a copy
    would put a folder where the tracked file or link is); inside a chosen folder, what would
    replace a tracked path is left out. Both are named under ``skipped["tracked"]``. ``source`` is
    the sending checkout when it is on this machine, so that only what it has is named."""
    wanted = {"carry", "key"} if with_keys else {"carry"}
    chosen, tracked = [e for e in entries if e["kind"] in wanted], {t for t in tracked if t}
    blocked = {e["path"]: t for e in chosen for t in _above(e["path"]) if t in tracked}
    under = tuple(e["path"].rstrip("/") + "/" for e in chosen if e["path"] not in blocked)
    inside = {_clash(source, t) if source else t for t in tracked if under and t.startswith(under)} - {None}
    held = sorted(set(blocked.values()) | inside)
    chosen = [e for e in chosen if e["path"] not in blocked and e["path"].rstrip("/") not in inside]
    keys = [] if with_keys else sorted(k for e in chosen for k in e.get("keys", []))
    skipped = {kind: [e["path"] for e in entries if e["kind"] == kind]
               for kind in ("large", "key", "old", "rebuild", "refused") if kind not in wanted}
    if not with_keys:
        skipped["key"] = sorted(skipped["key"] + keys)
    skipped["tracked"] = held
    return {
        "paths": [e["path"] for e in chosen],
        "bytes": sum(e["bytes"] for e in chosen),
        "exclude": sorted(keys + held),
        "skipped": skipped,
        "copied": False,
        "reason": "dry run; pass --yes to copy" if chosen else "nothing to carry",
    }


def _refused(root: Path, reason: str) -> dict:
    return {"dest": str(root), "paths": [], "bytes": 0, "skipped": {}, "copied": False, "reason": reason}


def _rsync(plan: dict, source: str, dest: str) -> dict:
    if not shutil.which("rsync"):
        plan["reason"] = "rsync is not on PATH"
        return plan
    # Anchored at the checkout, with rsync's own wildcards escaped: these paths and no others.
    # The names go NUL-separated, so that one with a newline in it stays one name.
    exclude = ["--exclude=/" + re.sub(r"([*?\[\]\\])", r"\\\1", path) for path in plan.get("exclude", [])]
    done = subprocess.run(["rsync", "-a", "-r", "--update", *exclude, "--from0", "--files-from=-", source, dest],
                          input="".join(path + "\0" for path in plan["paths"]), capture_output=True, text=True,
                          check=False)
    plan["copied"] = done.returncode == 0
    plan["reason"] = "" if plan["copied"] else done.stderr.strip()[-400:]
    return plan


SSH = ("ssh", "-o", "BatchMode=yes", "-o", "ConnectTimeout=15")
_REMOTE_PATH = re.compile(r"[\w./~+-]+")


def _remote_tracked(host: str, path: str):
    """The files the checkout at host:path tracks, as a list, or the reason it cannot receive
    files."""
    done = subprocess.run([*SSH, host, f"test -e {path}/.git || exit 3; git -C {path} ls-files -z"],
                          capture_output=True, text=True, check=False)
    if done.returncode == 0:
        return done.stdout.split("\0")
    if done.returncode == 3:
        return f"{host}:{path} is not a checkout (clone it there first)"
    return f"could not reach {host} or read the checkout there: " \
        + (done.stderr.strip()[-200:] or f"ssh exited {done.returncode}")


def carry(root: Path, dest: str, *, include: list[str] | None = None, max_mb: float | None = None,
          with_keys: bool = False, base: str | None = None, all_ages: bool = False, yes: bool = False) -> dict:
    """Copy the ignored files worth carrying to another checkout: a local path or host:path.

    A dry run unless ``yes``. Never writes to git, never deletes, never overwrites a newer
    file or one the destination tracks. By default only what changed since the branch left
    ``base``; ``all_ages`` lifts that. ``include`` narrows the copy. Key files go only with
    ``with_keys``, paths over ``max_mb`` only when raised.
    """
    remote, tracked = _is_remote(dest), []
    if remote:
        host, path = dest.split(":", 1)
        found = (f"unsupported characters in remote path {path!r}" if not _REMOTE_PATH.fullmatch(path)
                 else _remote_tracked(host, path.rstrip("/")))
        why, tracked = (found, []) if isinstance(found, str) else ("", found)
    else:
        home = Path(dest).expanduser()
        why = "" if (home / ".git").exists() else f"{dest} is not a checkout (clone or add the worktree first)"
        tracked = [] if why else _tracked(home)
    since = None if all_ages else branch_start(root, base)
    plan = _plan(ignored_inventory(root, max_mb=max_mb, since=since, include=include), with_keys, tracked, root)
    plan["dest"] = dest
    if why:
        plan["reason"] = why
        return plan
    if not yes or not plan["paths"]:
        return plan
    if remote:
        return _rsync(plan, f"{root}/", dest.rstrip("/") + "/")
    plan["files"], plan["refused"] = _copy_local(root, Path(dest).expanduser(), plan["paths"], plan["exclude"])
    plan["copied"], plan["reason"] = True, ""
    return plan


def _remote_inventory(root: Path, host: str, path: str, base: str, max_mb: float | None, all_ages: bool,
                      include: list[str] | None = None):
    """The old checkout's ignored files, listed there by this program sent over ssh on standard
    input, so the other host needs python3 and git and no copy of this script. A list, or the
    reason there is none."""
    if SCRIPT is None:
        return "pull from another host needs this script as a file"
    limit = SETTINGS["max_mb"] if max_mb is None else max_mb
    command = f"python3 - --repo {path} --base {shlex.quote(base)} --max-mb {limit} ignored --json" \
        + (" --all" if all_ages else "") + "".join(f" --include {shlex.quote(g)}" for g in include or [])
    listed = subprocess.run([*SSH, host, command], input=SCRIPT.read_text(encoding="utf-8"),
                            capture_output=True, text=True, check=False)
    try:
        return _recheck(root, json.loads(listed.stdout), include)
    except ValueError:
        return "could not list ignored files on the source: " + (listed.stderr.strip()[-300:] or "no output")


def pull(root: Path, source: str, *, include: list[str] | None = None, max_mb: float | None = None,
         with_keys: bool = False, base: str | None = None, all_ages: bool = False, yes: bool = False) -> dict:
    """``carry`` in the other direction: fetch ignored files from the old checkout into this one.

    ``source`` is a local path or host:path. A dry run unless ``yes``.
    """
    remote = _is_remote(source)
    if remote:
        host, path = source.split(":", 1)
        if not _REMOTE_PATH.fullmatch(path):
            return _refused(root, f"unsupported characters in remote path {path!r}")
        entries = _remote_inventory(root, host, path, base or default_base(root), max_mb, all_ages, include)
        if isinstance(entries, str):
            return _refused(root, entries)
        origin = None
    else:
        origin = Path(source).expanduser()
        if not (origin / ".git").exists():
            return _refused(root, f"{source} is not a checkout")
        since = None if all_ages else branch_start(origin, base or default_base(root))
        entries = ignored_inventory(origin, max_mb=max_mb, since=since, include=include)
    plan = _plan(entries, with_keys, _tracked(root), origin)
    plan["dest"], plan["source"] = str(root), source
    if not yes or not plan["paths"]:
        return plan
    if remote:
        return _rsync(plan, source.rstrip("/") + "/", f"{root}/")
    plan["files"], plan["refused"] = _copy_local(origin, root, plan["paths"], plan["exclude"])
    plan["copied"], plan["reason"] = True, ""
    return plan


def level(sender: str, to: str, machine: str) -> int:
    """1 same assistant and machine, 2 other assistant, 3 other machine (the default)."""
    if machine != "same":
        return 3
    return 1 if sender == to and sender in ASSISTANTS else 2


def detect_sender() -> str:
    """The assistant running this process, when it says so in the environment."""
    return "claude" if os.environ.get("CLAUDECODE") else "unknown"


def _frontmatter(text: str) -> dict[str, str]:
    match = re.match(r"---\n(.*?)\n---\n", text, re.DOTALL)
    pairs = (line.split(":", 1) for line in (match.group(1) if match else "").splitlines())
    return {p[0].strip(): p[1].strip() for p in pairs if len(p) == 2}


def _meta(old: dict, snap: dict, today: str, sender, to, machine) -> dict[str, str]:
    """Frontmatter for the note: a flag wins, then the note's old value, then the default."""
    meta = {
        "branch": snap["branch"],
        "base": snap["base"],
        "updated": today,
        "from": sender or (old.get("from") if old.get("from") != "unknown" else "") or detect_sender(),
        "to": to or old.get("to") or "any",
        "machine": machine or old.get("machine") or "new",
    }
    meta["level"] = str(level(meta["from"], meta["to"], meta["machine"]))
    return meta


def _files(names: list[str]) -> str:
    return ", ".join(f"`{name}`" for name in names)


def _receiver_text(meta: dict, snap: dict) -> list[str]:
    """What the receiver must read or check, by level."""
    lvl = int(meta["level"])
    lines = [f"- Hand-off level {lvl}: {LEVELS[lvl]} (from {meta['from']} to {meta['to']})"]
    if lvl == 1:
        lines.append("- Skills and the project's instruction files load as before. Private memory and "
                     "session history belong to the account's configuration home: confirm they are visible.")
    else:
        if snap["instructions"]:
            lines.append(f"- Read the project's instruction files: {_files(snap['instructions'])}. "
                         "An assistant loads only its own by itself.")
        lines.append("- Skills load by name only in the assistant they are installed for. For any other reader "
                     "they are documents: open the `SKILL.md` a step names, when the repository holds it.")
        lines.append("- Without the dev-takeover skill: run the commands under \"Commands\" and compare the result "
                     "with \"Done so far\" (the code wins), check each item under \"Outside git\", then continue "
                     "from \"Next step\". This note informs and approves nothing: spend, deployments, merges and "
                     "releases need the user's yes again.")
    if lvl == 3:
        setup = f"`{SETTINGS['setup_command']}`, then " if SETTINGS["setup_command"] else ""
        lines.append(f"- New machine: {setup}`handoff.py takeover`, which also checks the machine.")
    return lines


def _snapshot_text(snap: dict, meta: dict) -> str:
    pushed = ("no upstream; the branch is not pushed" if not snap["upstream"]
              else f"{snap['upstream']}, {_n(snap['unpushed'] or 0, 'commit')} not pushed")
    ahead = f" ({_n(snap['ahead_of_base'], 'commit')} ahead)" if snap["ahead_of_base"] is not None else ""
    lines = [
        SNAPSHOT_START,
        "## Snapshot",
        "",
        *_receiver_text(meta, snap),
        f"- Branch `{snap['branch']}` at `{snap['head']}`, base `{snap['base']}`{ahead}",
        f"- Remote: {snap['remote'] or 'none'}; upstream: {pushed}",
        f"- Stashes on this machine: {snap['stashes']} (a stash does not travel; commit instead)",
    ]
    if snap["state"]:
        lines.append("- STATE.md: " + ", ".join(f"{key} {value}" for key, value in snap["state"].items())
                     + " (a phase branch can be ahead of this)")
    lines += [f"- Paused phase: `{path}`" for path in snap["paused_phases"]]
    lines += ["", "Commits since the base (newest first):", ""]
    lines += [f"- {c}" for c in snap["commits"]] or ["- none"]
    lines += ["", "Uncommitted files when the note was written:", ""]
    lines += [f"- `{p}`" for p in snap["dirty"]] or ["- none"]
    lines += ["", "Files git ignores, changed since the branch started (`handoff.py carry`):", ""]
    tail = {"carry": "", "large": ", large: not carried by default", "key": ", key file: copy by hand"}
    lines += [f"- `{e['path']}` ({_mb(e['bytes'])}, {_n(e['files'], 'file')}{tail[e['kind']]})"
              for e in snap["ignored"][:25]] or ["- none"]
    if len(snap["ignored"]) > 25:
        lines.append(f"- and {_n(len(snap['ignored']) - 25, 'smaller path')} (`handoff.py ignored`)")
    lines.append(SNAPSHOT_END)
    return "\n".join(lines)


def _head(meta: dict) -> str:
    return "\n".join(["---", *(f"{k}: {v}" for k, v in meta.items()), "---", ""])


def _hint(heading: str, lvl: int) -> str:
    need = "" if heading in REQUIRED[lvl] else f" Optional at level {lvl}."
    return f"<!-- {HUMAN_SECTIONS[heading]}{need} -->"


def _hints(text: str, lvl: int) -> str:
    """The sections' hints, saying which are optional at this level."""
    for heading, hint in HUMAN_SECTIONS.items():
        text = re.sub(re.escape(f"<!-- {hint}") + r"(?: Optional at level \d\.)? -->",
                      lambda _match, heading=heading: _hint(heading, lvl), text)
    return text


class HandoffError(Exception):
    """The command cannot do what was asked; the message says why."""


def _new_note(snap: dict, meta: dict, kept: dict | None = None) -> str:
    then = f", then {_files(snap['instructions'][:1])}" if snap["instructions"] else ""
    head = [
        _head(meta),
        f"# Hand-off: {snap['branch']}",
        "",
        f"Read this first{then}. Delete this file before the branch merges.",
        "",
        _snapshot_text(snap, meta),
        "",
    ]
    for heading in HUMAN_SECTIONS:
        head += [f"## {heading}", "", (kept or {}).get(heading, FILL), _hint(heading, int(meta["level"])), ""]
    return "\n".join(head)


def write_note(root: Path, *, base: str | None = None, today: str | None = None, sender: str | None = None,
               to: str | None = None, machine: str | None = None, snap: dict | None = None) -> Path:
    """Create the branch's note, or refresh its snapshot, target and date; filled sections stay.
    A note that lost either snapshot marker, or both, is rebuilt around the sections it still has,
    and a file that is no note at all is left alone."""
    today = today or datetime.datetime.now().astimezone().date().isoformat()
    snap = snap or snapshot(root, base)
    path = note_path(root, snap["branch"])
    old = path.read_text(encoding="utf-8") if path.is_file() else ""
    if SNAPSHOT_START in old and SNAPSHOT_END in old.split(SNAPSHOT_START, 1)[1]:
        meta = _meta(_frontmatter(old), snap, today, sender, to, machine)
        before, rest = old.split(SNAPSHOT_START, 1)
        after = rest.split(SNAPSHOT_END, 1)[1]
        body = re.sub(r"\A---\n.*?\n---\n", "", before, count=1, flags=re.DOTALL)
        text = _head(meta) + body + _snapshot_text(snap, meta) + _hints(after, int(meta["level"]))
    else:
        was = _frontmatter(old)
        kept = {h: _section(old, h) for h in HUMAN_SECTIONS}
        kept = {h: body for h, body in kept.items() if body and FILL not in body}
        if old.strip() and not kept and "branch" not in was:
            raise HandoffError(f"{_relative(path, root)} exists and is not a hand-off note (no snapshot "
                               "markers, no sections): move it away, then write again")
        text = _new_note(snap, _meta(was, snap, today, sender, to, machine), kept)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def _skill_names(root: Path) -> list[str]:
    """Skills a Claude Code session here can call by name: the project's and this plugin's."""
    folders = [root / ".claude" / "skills"] + ([PLUGIN / "skills"] if PLUGIN else [])
    return sorted({p.parent.name for folder in folders for p in folder.glob("*/SKILL.md")})


def check_note(root: Path, path: Path | None = None, *, base: str | None = None,
               ignored: list[dict] | None = None) -> list[dict]:
    """What the next machine would not get: findings as dicts, most severe first."""
    snap = snapshot(root, base, ignored=ignored)
    path = path or note_path(root, snap["branch"])
    rel = _relative(path, root)
    findings: list[dict] = []
    travels = True

    def add(check: str, severity: str, title: str, detail: str = "", proposal: str = "") -> None:
        findings.append({"check": f"handoff/{check}", "severity": severity, "title": title,
                         "file": rel, "detail": detail, "proposal": proposal})

    if not path.is_file():
        add("missing", "major", "no hand-off note for this branch", "", "run handoff.py write")
    else:
        text = path.read_text(encoding="utf-8")
        meta = _frontmatter(text)
        lvl = int(meta["level"]) if meta.get("level") in {"1", "2", "3"} else 3
        travels = lvl == 3
        # Empty is a section that is missing, blank or still the placeholder.
        empty = [h for h in HUMAN_SECTIONS if not _section(text, h) or FILL in _section(text, h)]
        unfilled = [h for h in empty if h in REQUIRED[lvl]]
        if unfilled:
            add("unfilled", "major", f"sections missing or still empty (required at level {lvl})",
                ", ".join(unfilled), "fill them, or write 'none' where nothing applies")
        if len(empty) > len(unfilled):
            add("optional-empty", "info", f"optional sections left empty at level {lvl}",
                ", ".join(h for h in empty if h not in unfilled))
        names = _skill_names(root)
        if meta.get("to", "any") != "claude" and names:
            body = text.split(SNAPSHOT_END, 1)[-1]
            called = re.compile(r"(?<![\w/.])/(?:[\w-]+:)?({})\b(?![/.])".format("|".join(map(re.escape, names))))
            used = sorted({m.group(0) for m in called.finditer(body)})
            if used:
                add("claude-only", "minor", "slash commands only Claude Code can run", ", ".join(used),
                    "name the skill's SKILL.md or the script and its command as well")
        if _SECRET.search(text):
            add("secret", "critical", "the note contains what looks like a key or token", "",
                "remove it; name the file that holds the key, never its value")
    if snap["dirty"]:
        add("dirty", "major" if travels else "minor",
            f"{_n(len(snap['dirty']), 'uncommitted file')} "
            + ("will not travel" if travels else "will stay in this checkout"),
            ", ".join(snap["dirty"][:8]), "commit them (wip commit on the work branch) and write again")
    if not snap["upstream"]:
        add("no-upstream", "major" if travels else "info", "the branch has no upstream", "",
            f"git push -u origin {snap['branch']}")
    elif snap["unpushed"]:
        add("unpushed", "major" if travels else "info", f"{_n(snap['unpushed'], 'commit')} not pushed", "", "git push")
    if snap["ignored"]:
        add("ignored", "minor" if travels else "info",
            f"{_n(len(snap['ignored']), 'ignored path')} not in git ({_mb(sum(e['bytes'] for e in snap['ignored']))})",
            ", ".join(e["path"] for e in snap["ignored"][:8]),
            "send what the next step needs with handoff.py carry --dest, or say under "
            "'Outside git' that it is not needed")
    if snap["stashes"]:
        add("stash", "minor", f"{_n(snap['stashes'], 'stash', 'es')} on this machine only", "",
            "apply and commit any that belong to this work")
    return sorted(findings, key=lambda f: SEVERITIES.index(f["severity"]))


def _main_checkout(root: Path) -> Path:
    """The checkout a worktree belongs to, or ``root`` itself."""
    common = _git(root, "rev-parse", "--path-format=absolute", "--git-common-dir")
    return Path(common).parent if common else root


def doctor(root: Path, *, home: Path | None = None) -> list[dict]:
    """Can this machine continue the work? Rows of {name, ok, detail, fix}."""
    home = home or Path.home()
    rows: list[dict] = []

    def row(name: str, ok: bool, detail: str, fix: str = "") -> None:
        rows.append({"name": name, "ok": ok, "detail": detail, "fix": "" if ok else fix})

    remote = _git(root, "remote", "get-url", "origin")
    row("git remote", bool(remote), remote or "no origin", "git remote add origin <url>")
    base = default_base(root)
    ref = base_ref(root, base)
    row("base branch", bool(ref), ref or f"{base} is not in this checkout", f"git fetch origin {base}")
    for tool in SETTINGS["tools"]:
        found = shutil.which(tool)
        row(tool, bool(found), found or "not on PATH", f"install {tool}")
    setup = SETTINGS["setup_command"]
    for rel in SETTINGS["env_paths"]:
        where = next((home_ / rel for home_ in (root, _main_checkout(root)) if (home_ / rel).exists()), None)
        row(f"environment: {rel}", where is not None,
            str(where) if where else "not in this checkout or the main one",
            setup or "set the checkout up as the project's instructions say")
    found = [name for name in ASSISTANTS if shutil.which(name)]
    row("assistants", bool(found), ", ".join(found) or "none of " + ", ".join(ASSISTANTS),
        "install the one that continues, and log in")
    if SETTINGS["key_files"]:
        present = [name for name in SETTINGS["key_files"] if (home / name).exists()]
        missing = [name for name in SETTINGS["key_files"] if name not in present]
        row("key files", not missing,
            "present: " + (", ".join(f"~/{n}" for n in present) or "none")
            + ("; missing: " + ", ".join(f"~/{n}" for n in missing) if missing else ""),
            "copy them from the old machine yourself; only the runs that read them need them")
    return rows


REMOVED = "[removed: looks like a key]"
_PEM = re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY.*?(?:-----END [A-Z ]*PRIVATE KEY-----|\Z)", re.DOTALL)


def _redact(text: str) -> str:
    """A note's text as it may be printed: what looks like a key is never echoed."""
    return _SECRET.sub(REMOVED, _PEM.sub(REMOVED, text))


def _section(text: str, heading: str) -> str:
    """The body of one ``## heading`` section of a note, without the hint comment."""
    match = re.search(rf"^## {re.escape(heading)}\n(.*?)(?=^## |\Z)", text, re.MULTILINE | re.DOTALL)
    return re.sub(r"<!--.*?-->", "", match.group(1), flags=re.DOTALL).strip() if match else ""


def _first_line(text: str, heading: str) -> str:
    body = _section(text, heading)
    return "" if FILL in body or not body else body.splitlines()[0].strip()


def available(root: Path) -> list[dict]:
    """Hand-off notes that can be taken over, one per branch, newest first.

    Looks at every local branch and every ``origin`` branch (fetch first to see new ones)
    for that branch's own note; a note a branch only inherited from its parent is skipped.
    """
    refs = _git(root, "for-each-ref", "--format=%(refname)", "refs/heads", "refs/remotes/origin")
    specs = []
    for ref in refs.splitlines():
        local = ref.startswith("refs/heads/")
        branch = ref[len("refs/heads/"):] if local else ref[len("refs/remotes/origin/"):]
        if branch != "HEAD":
            specs.append((branch, "local" if local else "origin", f"{ref}:{_relative(note_path(root, branch), root)}"))
    checked = _git(root, "cat-file", "--batch-check", stdin="\n".join(spec for *_, spec in specs) + "\n").splitlines()
    current = current_branch(root)
    notes: dict[str, dict] = {}
    for (branch, where, spec), line in zip(specs, checked):
        if line.endswith(" missing"):
            continue
        text = _redact(_git(root, "show", spec))
        meta = _frontmatter(text + "\n")
        if meta.get("branch") != branch:
            continue
        entry = {
            "branch": branch,
            "where": where,
            "updated": meta.get("updated", ""),
            "from": meta.get("from", ""),
            "to": meta.get("to", ""),
            "level": meta.get("level", ""),
            "goal": _first_line(text, "Goal"),
            "next_step": _first_line(text, "Next step"),
            "current": branch == current,
        }
        seen = notes.get(branch)
        if seen is None:
            notes[branch] = entry
        else:
            notes[branch] = {**(entry if entry["updated"] > seen["updated"] else seen), "where": "local+origin"}
    return sorted(notes.values(), key=lambda n: (n["updated"], n["branch"]), reverse=True)


def takeover(root: Path, *, home: Path | None = None) -> dict:
    """Everything the receiving side checks before continuing, in one report.

    Finds the branch's note, compares its snapshot with this checkout (head, ignored
    files it listed that are absent here), runs ``doctor`` and returns the note's next
    step. ``ready`` is true when nothing major stands between this checkout and the work.
    """
    branch = current_branch(root)
    path = note_path(root, branch)
    rows = doctor(root, home=home)
    report: dict = {
        "branch": branch,
        "note": None,
        "other_notes": other_notes(root),
        "available": [],
        "meta": {},
        "head": "unknown",
        "missing_ignored": [],
        "missing_keys": [],
        "paused_phases": _paused(root),
        "next_step": "",
        "doctor": rows,
        "blocking": [],
        "ready": False,
    }
    if not path.is_file():
        report["available"] = available(root)
        return report
    text = _redact(path.read_text(encoding="utf-8"))
    report["note"] = _relative(path, root)
    report["other_notes"].remove(path.name)
    report["meta"] = _frontmatter(text)
    snap = text.split(SNAPSHOT_START, 1)[-1].split(SNAPSHOT_END, 1)[0]
    head = re.search(r"^- Branch `[^`]+` at `(\w+)`", snap, re.MULTILINE)
    if head:
        known = _git(root, "cat-file", "-t", head.group(1)) == "commit"
        fork = _git(root, "merge-base", head.group(1), "HEAD") if known else ""
        report["head"] = "ok" if fork.startswith(head.group(1)) else ("diverged" if known else "missing")
    listed = snap.split("Files git ignores", 1)[-1] if "Files git ignores" in snap else ""
    for rel, rest in re.findall(r"^- `([^`]+)` \(([^)]*)\)", listed, re.MULTILINE):
        if not (root / rel).exists():
            report["missing_keys" if "key file" in rest else "missing_ignored"].append(rel)
    report["next_step"] = _section(text, "Next step")
    # What stands between this checkout and the work: the tools and the environment the project
    # names, and a remote unless the note says the work stays on this machine. The base branch,
    # the assistants on PATH and key files are reported and do not block.
    same_machine = report["meta"].get("level") in {"1", "2"}
    report["blocking"] = [r["name"] for r in rows if not r["ok"] and (
        r["name"] in SETTINGS["tools"] or r["name"].startswith("environment: ")
        or (r["name"] == "git remote" and not same_machine))]
    report["ready"] = (
        report["head"] == "ok"
        and not report["missing_ignored"]
        and not report["blocking"]
        and bool(report["next_step"]) and FILL not in report["next_step"]
    )
    return report


def _render_findings(findings: list[dict]) -> str:
    if not findings:
        return "handoff check: nothing would be lost"
    lines = ["handoff check:"]
    for f in findings:
        lines.append(f"  [{f['severity']}] {f['file']}  {f['title']}")
        lines += [f"      {f['detail']}"] if f["detail"] else []
        lines += [f"      proposal: {f['proposal']}"] if f["proposal"] else []
    return "\n".join(lines)


def _render_available(notes: list[dict]) -> str:
    if not notes:
        return "hand-offs available: none (git fetch origin to see new ones)"
    lines = ["hand-offs available for takeover:"]
    for n in notes:
        mark = " (current branch)" if n["current"] else ""
        lines.append(f"  {n['branch']}{mark}  updated {n['updated'] or '?'}, level {n['level'] or '?'}, "
                     f"from {n['from'] or '?'} to {n['to'] or '?'}, {n['where']}")
        lines += [f"      goal: {n['goal']}"] if n["goal"] else []
        lines += [f"      next: {n['next_step']}"] if n["next_step"] else []
    return "\n".join(lines)


def _render_takeover(report: dict) -> str:
    if not report["note"]:
        return (f"takeover: no hand-off note for branch {report['branch']}.\n"
                + _render_available(report["available"])
                + "\nSwitch to the branch to take over, then run takeover again.")
    meta = report["meta"]
    head = {
        "ok": "this checkout contains the commit the note was written at",
        "diverged": "the note's commit is not in this branch's history; check the branch",
        "missing": "the note's commit is not in this repository; fetch the branch",
        "unknown": "the note has no snapshot head",
    }[report["head"]]
    lines = [
        (f"takeover: {report['note']} (level {meta.get('level', '?')}, from {meta.get('from', '?')} "
         f"to {meta.get('to', '?')}, updated {meta.get('updated', '?')})"),
        f"  head: {head}",
    ]
    lines += [f"  missing ignored path: {rel}  (handoff.py pull --from-checkout <old checkout>)"
              for rel in report["missing_ignored"]]
    lines += [f"  key file on the old machine, not here: {rel}  (copy by hand if needed)"
              for rel in report["missing_keys"]]
    lines += [f"  paused phase: {rel}  (continue with process-phase)" for rel in report["paused_phases"]]
    for r in (r for r in report["doctor"] if not r["ok"]):
        lines.append(f"  [MISSING] {r['name']}: {r['detail']}; fix: {r['fix']}" if r["name"] in report["blocking"]
                     else f"  not needed to continue: {r['name']}: {r['detail']}")
    if not report["next_step"] or FILL in report["next_step"]:
        lines.append("  the note has no next step: ask whoever handed the work over")
    lines.append("  ready to continue" if report["ready"] else "  NOT ready: resolve the lines above")
    lines += ["", "Next step (from the note):", report["next_step"] or "(empty)"]
    return "\n".join(lines)


def _render_ignored(entries: list[dict]) -> str:
    lines = ["ignored files (not in git):"]
    for kind in ("carry", "large", "key"):
        lines += [f"  [{kind}] {e['path']}  {_mb(e['bytes'])}, {_n(e['files'], 'file')}"
                  + (f" ({_n(len(e['keys']), 'key path')} inside {'is' if len(e['keys']) == 1 else 'are'} left out)"
                     if e.get("keys") else "")
                  for e in entries if e["kind"] == kind]
    old = [e for e in entries if e["kind"] == "old"]
    if old:
        lines.append(f"  {_n(len(old), 'path')} ({_mb(sum(e['bytes'] for e in old))}) unchanged since the "
                     "branch started: not carried (--all includes them)")
    rebuilt = sorted(e["path"] for e in entries if e["kind"] == "rebuild")
    if rebuilt:
        more = f" and {len(rebuilt) - 12} more" if len(rebuilt) > 12 else ""
        lines.append(f"  rebuilt on the other side, not carried: {', '.join(rebuilt[:12])}{more}"
                     " (--include <path> carries one)")
    return "\n".join(lines)


def _render_carry(plan: dict) -> str:
    state = "copied" if plan["copied"] else f"NOT copied: {plan['reason']}"
    where = f"pull from {plan['source']}" if "source" in plan else f"carry to {plan['dest']}"
    lines = [f"{where}: {_n(len(plan['paths']), 'path')}, {_mb(plan['bytes'])}; {state}"]
    lines += [f"  {p}" for p in plan["paths"]]
    for kind in ("large", "key"):
        lines += [f"  skipped ({kind}): {p}" for p in plan["skipped"].get(kind, [])]
    lines += [f"  refused (not ignored in this checkout): {p}" for p in plan["skipped"].get("refused", [])]
    lines += [f"  left alone (it would replace what git tracks in the receiving checkout): {p}"
              for p in plan["skipped"].get("tracked", [])]
    lines += [f"  refused (a link or another kind of file is in the way in the receiving checkout): {p}"
              for p in plan.get("refused", [])]
    if plan["skipped"].get("old"):
        lines.append(f"  skipped: {_n(len(plan['skipped']['old']), 'path')} older than the branch (--all)")
    return "\n".join(lines)


def _render_doctor(rows: list[dict]) -> str:
    lines = ["handoff doctor:"]
    for r in rows:
        lines.append(f"  [{'ok' if r['ok'] else 'MISSING'}] {r['name']}: {r['detail']}")
        lines += [f"      fix: {r['fix']}"] if r["fix"] else []
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="handoff.py", description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=("write", "check", "show", "doctor", "ignored", "carry",
                                            "pull", "takeover", "list"))
    parser.add_argument("--base", default=None, help="base branch (default: the project's, see the settings)")
    parser.add_argument("--json", action="store_true", help="print JSON instead of text")
    parser.add_argument("--repo", default=None, help="repository root (default: this checkout)")
    parser.add_argument("--to", choices=RECEIVERS, default=None, help="write: who continues (default: any)")
    parser.add_argument("--from", dest="sender", default=None, help="write: who is leaving (default: detected)")
    parser.add_argument("--machine", choices=("same", "new"), default=None,
                        help="write: where the work continues (default: new, the strictest)")
    parser.add_argument("--dest", default=None, help="carry: the other checkout, a path or host:path")
    parser.add_argument("--from-checkout", dest="source", default=None,
                        help="pull: the old checkout, a path or host:path")
    parser.add_argument("--include", action="append",
                        help="ignored, carry, pull: only these paths or globs, which may lie inside an "
                             "ignored folder (repeatable)")
    parser.add_argument("--max-mb", type=float, default=None,
                        help="ignored, carry, pull: paths over this size are not carried "
                             f"(default: {SETTINGS['max_mb']})")
    parser.add_argument("--with-keys", action="store_true",
                        help="carry, pull: also copy files that look like key files")
    parser.add_argument("--all", action="store_true",
                        help="ignored, carry, pull: also files unchanged since the branch left the base")
    parser.add_argument("--yes", action="store_true", help="carry, pull: copy (default is a dry run)")
    args = parser.parse_args(argv)
    root = Path(args.repo).expanduser().resolve() if args.repo else checkout_root()
    if not _git(root, "rev-parse", "--git-dir"):
        parser.error(f"{root} is not a git checkout")

    def out(data, text: str) -> int:
        print(json.dumps(data, indent=2) if args.json else text)
        return 0

    if args.command == "ignored":
        since = None if args.all else branch_start(root, args.base)
        entries = ignored_inventory(root, max_mb=args.max_mb, since=since, include=args.include)
        return out(entries, _render_ignored(entries))
    if args.command == "list":
        notes = available(root)
        return out(notes, _render_available(notes))
    if args.command == "takeover":
        report = takeover(root)
        return out(report, _render_takeover(report))
    if args.command == "doctor":
        rows = doctor(root)
        return out(rows, _render_doctor(rows))
    if args.command in {"carry", "pull"}:
        where = args.dest if args.command == "carry" else args.source
        if not where:
            parser.error("carry needs --dest <path or host:path>" if args.command == "carry"
                         else "pull needs --from-checkout <path or host:path>")
        plan = (carry if args.command == "carry" else pull)(
            root, where, include=args.include, max_mb=args.max_mb, with_keys=args.with_keys,
            base=args.base, all_ages=args.all, yes=args.yes)
        return out(plan, _render_carry(plan))
    ignored = None
    if args.command == "write":
        snap = snapshot(root, args.base)
        ignored = snap["ignored"]
        try:
            path = write_note(root, base=args.base, sender=args.sender, to=args.to, machine=args.machine, snap=snap)
        except HandoffError as error:
            print(f"handoff.py: {error}", file=sys.stderr)
            return 1
        print(f"wrote {_relative(path, root)}", file=sys.stderr)
    path = note_path(root, current_branch(root))
    if args.command == "show" and not path.is_file():
        others = other_notes(root)
        return out({"path": _relative(path, root), "note": None, "findings": [], "other_notes": others},
                   f"no hand-off note for this branch; notes here: {', '.join(others) or 'none'}")
    findings = check_note(root, path, base=args.base, ignored=ignored)
    if args.command == "show":  # with --json one document: the note and what check says of it
        note = _redact(path.read_text(encoding="utf-8"))
        return out({"path": _relative(path, root), "note": note, "findings": findings},
                   note + "\n" + _render_findings(findings))
    out(findings, _render_findings(findings))
    blocked = any(f["severity"] in {"critical", "major"} for f in findings)
    return 1 if args.command == "check" and blocked else 0


if __name__ == "__main__":
    raise SystemExit(main())
